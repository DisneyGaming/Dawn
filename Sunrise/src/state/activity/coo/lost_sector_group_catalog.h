[[nodiscard]] constexpr bool required(std::uint32_t scenario,std::uint32_t object,
    std::uint32_t key,std::uint64_t sliceMask) noexcept {
    for(const auto& group:kRegistryGroups)
        if(group.scenario==scenario && group.object==object && group.key==key
            && group.sliceMask==sliceMask)return true;
    return false;
}

[[nodiscard]] constexpr std::size_t source_count(std::uint32_t scenario) noexcept {
    std::size_t result{};
    for(const auto& group:kRegistryGroups)if(group.scenario==scenario)result+=group.sourceCount;
    return result;
}

